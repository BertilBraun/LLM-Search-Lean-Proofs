"""Step-by-step replay of public proofs in the pinned Lean environment into (state, step, state, remaining) records."""

import asyncio
import hashlib
import logging
import re
import time
from collections import Counter, defaultdict
from collections.abc import Awaitable, Callable, Iterable, Sequence
from dataclasses import dataclass

from lean_search.corpora.decontamination import canonical_statement
from lean_search.corpora.normalize import short_hash
from lean_search.corpora.records import DataSplit, ProofRecord, TracedProof, TracedStep, TracePath, TraceStatus
from lean_search.lean import (
    LeanError,
    LeanRepl,
    LeanReplConfig,
    LeanReplPool,
    LeanTimeout,
    ProofState,
    ReplFailure,
    ReplFailureKind,
    VerificationResult,
    split_tactics,
)

TRACE_ORDER = (
    "goedel_lean_workbook_proofs",
    "stp_lean_workbook",
    "deepseek_prover_v1",
    "lean_workbook",
    "goedel_sft_v2",
    "numinamath_lean_kimina",
    "numinamath_lean_human",
    "leanabell_sft",
)
# Generated by self-play seeded from miniF2F, mostly its valid split.
EXCLUDED_SOURCES = frozenset({"stp_conjectures"})
VALIDATION_FRACTION = 0.02
VERIFICATION_FRACTION = 0.02
FOREIGN_HEADER_BATCH_SIZE = 32
WHOLE_PROOF_CHECKED = frozenset({TraceStatus.STEP_ERROR, TraceStatus.CLOSED_EARLY, TraceStatus.GOALS_REMAINING})
PROBLEMS_KEPT = 3
PROBLEM_CHARACTERS = 500
HEADER_FAILURE_PREFIX = "The header does not elaborate"
_PARSE_ERROR = re.compile(r"<input>:\d+:\d+: ")
logger = logging.getLogger(__name__)

type StepFailure = LeanError | LeanTimeout | ReplFailure


@dataclass(frozen=True)
class TracingLimits:
    heartbeats: int
    timeout_seconds: float


@dataclass(frozen=True)
class StepRun:
    states: tuple[ProofState, ...]
    step_seconds: tuple[float, ...]
    failure: StepFailure | None
    failing_step: str


@dataclass(frozen=True)
class Attempt:
    path: TracePath
    status: TraceStatus
    total_steps: int
    states: tuple[ProofState, ...]
    step_seconds: tuple[float, ...]
    failure: StepFailure | None
    failing_step: str


@dataclass(frozen=True)
class ProofTrace:
    proof: TracedProof
    steps: tuple[TracedStep, ...]


@dataclass(frozen=True)
class TracingShard:
    source: str
    name: str
    records: tuple[ProofRecord, ...]

    @property
    def key(self) -> str:
        return f"{self.source}/{self.name}"


@dataclass(frozen=True)
class TracingBatch:
    shard_key: str
    header: str
    records: tuple[ProofRecord, ...]


def stable_fraction(text: str, purpose: str) -> float:
    digest = hashlib.sha256(f"{purpose}\n{text}".encode()).digest()
    return int.from_bytes(digest[:8], "big") / 2**64


def statement_key(formal_statement: str) -> str:
    return short_hash(canonical_statement(formal_statement))


def assign_split(formal_statement: str) -> DataSplit:
    # Keyed on the canonical statement: sources name the same statement differently (12% of statements).
    if stable_fraction(statement_key(formal_statement), "split") < VALIDATION_FRACTION:
        return DataSplit.VALIDATION
    return DataSplit.TRAIN


def in_verification_sample(proof_identifier: str) -> bool:
    return stable_fraction(proof_identifier, "verification") < VERIFICATION_FRACTION


def is_parse_error(failure: StepFailure | None) -> bool:
    match failure:
        case LeanError(message=message):
            return _PARSE_ERROR.match(message) is not None
        case _:
            return False


def attempt_status(failure: StepFailure | None, last_state: ProofState) -> TraceStatus:
    match failure:
        case None if last_state.is_proved:
            return TraceStatus.COMPLETE
        case None:
            return TraceStatus.GOALS_REMAINING
        case LeanError() if last_state.is_proved:
            return TraceStatus.CLOSED_EARLY
        case LeanError():
            return TraceStatus.STEP_ERROR
        case LeanTimeout():
            return TraceStatus.TIMEOUT
        case ReplFailure():
            return TraceStatus.REPL_FAILURE


def traced_steps(
    record: ProofRecord, split: DataSplit, states: Sequence[ProofState], step_seconds: Sequence[float]
) -> tuple[TracedStep, ...]:
    # Steps after the goals are closed (`all_goals ...`, `try ...`) succeed as no-ops and are not training data.
    total_steps = next(index for index, state in enumerate(states) if state.is_proved)
    states, step_seconds = states[: total_steps + 1], step_seconds[:total_steps]
    return tuple(
        TracedStep(
            source=record.source,
            proof_identifier=record.identifier,
            statement_identifier=record.statement_identifier,
            split=split,
            header=record.header,
            formal_statement=record.formal_statement,
            step_index=index,
            total_steps=total_steps,
            remaining_steps=total_steps - index,
            goals_before=before.goals,
            step=after.tactics[-1],
            goals_after=after.goals,
            previous_steps=before.tactics,
            heartbeats=after.tactic_heartbeats[-1],
            elapsed_seconds=seconds,
        )
        for index, (before, after, seconds) in enumerate(zip(states[:-1], states[1:], step_seconds, strict=True))
    )


def state_before(step: TracedStep) -> ProofState:
    # Session 0 is never live, so the REPL rebuilds this state by replaying `previous_steps` from the statement.
    heartbeats = (step.heartbeats,) * len(step.previous_steps)
    return ProofState(step.header, step.formal_statement, step.previous_steps, step.goals_before, -1, 0, heartbeats)


def shortened(problems: Sequence[str]) -> tuple[str, ...]:
    return tuple(problem[:PROBLEM_CHARACTERS] for problem in problems[:PROBLEMS_KEPT])


def _failure_fields(failure: StepFailure | None) -> tuple[str, str]:
    match failure:
        case None:
            return "", ""
        case ReplFailure(kind=kind, message=message):
            return message, str(kind)
        case LeanError(message=message) | LeanTimeout(message=message):
            return message, ""


def start_failure_trace(
    record: ProofRecord, failure: StepFailure, start_seconds: float, limits: TracingLimits
) -> ProofTrace:
    message, repl_failure_kind = _failure_fields(failure)
    status = TraceStatus.REPL_FAILURE if repl_failure_kind else TraceStatus.START_FAILURE
    proof = TracedProof(
        source=record.source,
        proof_identifier=record.identifier,
        statement_identifier=record.statement_identifier,
        split=assign_split(record.formal_statement),
        header=record.header,
        formal_statement=record.formal_statement,
        status=status,
        path=TracePath.STEPS,
        total_steps=len(split_tactics(record.tactic_proof)),
        applied_steps=(),
        open_goals=0,
        failing_step_index=None,
        failing_step="",
        failure_message=message,
        repl_failure_kind=repl_failure_kind,
        heartbeats=limits.heartbeats,
        start_seconds=start_seconds,
        step_seconds=(),
        elapsed_seconds=start_seconds,
        verification_seconds=0.0,
        verified=None,
        plain_verified=None,
        verification_problems=(),
        whole_proof_verified=None,
        whole_proof_problems=(),
    )
    return ProofTrace(proof, ())


async def apply_steps(repl: LeanRepl, root: ProofState, steps: Sequence[str], limits: TracingLimits) -> StepRun:
    states = [root]
    seconds: list[float] = []
    for step in steps:
        result = await repl.apply_tactic(states[-1], step, limits.heartbeats, limits.timeout_seconds)
        seconds.append(result.elapsed_seconds)
        match result.outcome:
            case ProofState() as state:
                states.append(state)
            case failure:
                return StepRun(tuple(states), tuple(seconds), failure, step)
    return StepRun(tuple(states), tuple(seconds), None, "")


def _step_attempt(path: TracePath, run: StepRun, total_steps: int) -> Attempt:
    status = attempt_status(run.failure, run.states[-1])
    return Attempt(path, status, total_steps, run.states, run.step_seconds, run.failure, run.failing_step)


async def attempt_proof(repl: LeanRepl, root: ProofState, tactic_proof: str, limits: TracingLimits) -> Attempt:
    steps = split_tactics(tactic_proof)
    run = await apply_steps(repl, root, steps, limits)
    if not is_parse_error(run.failure):
        return _step_attempt(TracePath.STEPS, run, len(steps))
    # A piece that does not parse alone: `apply_block` merges pieces on incomplete input.
    block = await repl.apply_block(root, tactic_proof, limits.heartbeats, limits.timeout_seconds)
    if block.failure is not None:
        states = (root, block.state) if block.applied_tactics else (root,)
        status = attempt_status(block.failure, block.state)
        return Attempt(TracePath.BLOCK, status, block.total_tactics, states, (), block.failure, "")
    attempt = _step_attempt(
        TracePath.BLOCK, await apply_steps(repl, root, block.state.tactics, limits), block.total_tactics
    )
    if attempt.status is TraceStatus.COMPLETE and len(block.applied_tactics) < block.total_tactics:
        return Attempt(
            TracePath.BLOCK,
            TraceStatus.CLOSED_EARLY,
            block.total_tactics,
            attempt.states,
            attempt.step_seconds,
            LeanError("The proof closed before its last step."),
            "",
        )
    return attempt


async def trace_proof(repl: LeanRepl, record: ProofRecord, limits: TracingLimits, verify: bool) -> ProofTrace:
    started = time.monotonic()
    start = await repl.start_proof(record.formal_statement, record.header)
    match start.outcome:
        case ProofState() as root:
            attempt = await attempt_proof(repl, root, record.tactic_proof, limits)
        case failure:
            return start_failure_trace(record, failure, start.elapsed_seconds, limits)
    elapsed_seconds = time.monotonic() - started
    verification: VerificationResult | None = None
    if verify and attempt.status is TraceStatus.COMPLETE:
        verification = await repl.verify_state(attempt.states[-1])
    whole_proof: VerificationResult | None = None
    if attempt.status in WHOLE_PROOF_CHECKED:
        # Separates proofs that do not compile here from proofs that only fail when replayed step by step.
        whole_proof = await repl.verify_proof(record.formal_statement, record.tactic_proof, record.header)
    split = assign_split(record.formal_statement)
    message, repl_failure_kind = _failure_fields(attempt.failure)
    last_state = attempt.states[-1]
    proof = TracedProof(
        source=record.source,
        proof_identifier=record.identifier,
        statement_identifier=record.statement_identifier,
        split=split,
        header=record.header,
        formal_statement=record.formal_statement,
        status=attempt.status,
        path=attempt.path,
        total_steps=attempt.total_steps,
        applied_steps=last_state.tactics,
        open_goals=len(last_state.goals),
        failing_step_index=None if attempt.failure is None else len(last_state.tactics),
        failing_step=attempt.failing_step,
        failure_message=message,
        repl_failure_kind=repl_failure_kind,
        heartbeats=limits.heartbeats,
        start_seconds=start.elapsed_seconds,
        step_seconds=attempt.step_seconds,
        elapsed_seconds=elapsed_seconds,
        verification_seconds=0.0 if verification is None else verification.elapsed_seconds,
        verified=None if verification is None else verification.verified,
        plain_verified=None if verification is None else verification.plain_verified,
        verification_problems=() if verification is None else verification.problems,
        whole_proof_verified=None if whole_proof is None else whole_proof.verified,
        whole_proof_problems=() if whole_proof is None else shortened(whole_proof.problems),
    )
    if attempt.status is not TraceStatus.COMPLETE:
        return ProofTrace(proof, ())
    return ProofTrace(proof, traced_steps(record, split, attempt.states, attempt.step_seconds))


def _is_header_failure(trace: ProofTrace) -> bool:
    return trace.proof.status is TraceStatus.START_FAILURE and trace.proof.failure_message.startswith(
        HEADER_FAILURE_PREFIX
    )


async def trace_batch(
    pool: LeanReplPool, batch: TracingBatch, preloaded_header: str, limits: TracingLimits
) -> list[ProofTrace]:
    traces: list[ProofTrace] = []
    async with pool.acquire() as repl:
        foreign = batch.header != preloaded_header
        if foreign:
            # A second header re-imports Mathlib onto the heap (~4 GiB), so each process keeps one header.
            await repl.restart()
        for record in batch.records:
            if traces and _is_header_failure(traces[-1]):
                failure = LeanError(traces[-1].proof.failure_message)
                traces.append(start_failure_trace(record, failure, 0.0, limits))
            else:
                traces.append(await trace_proof(repl, record, limits, in_verification_sample(record.identifier)))
        if foreign:
            await repl.restart()
            await repl.load_header(preloaded_header)
    return traces


def repl_failure_traces(batch: TracingBatch, error: Exception, limits: TracingLimits) -> list[ProofTrace]:
    failure = ReplFailure(ReplFailureKind.CRASHED, f"The batch failed: {error!r}")
    return [start_failure_trace(record, failure, 0.0, limits) for record in batch.records]


def _chunks(source: str, part: str, records: Sequence[ProofRecord], shard_size: int) -> list[TracingShard]:
    return [
        TracingShard(source, f"{part}_{number:04d}", tuple(records[start : start + shard_size]))
        for number, start in enumerate(range(0, len(records), shard_size))
    ]


def plan_shards(records: Iterable[ProofRecord], pilot_size: int, shard_size: int) -> list[TracingShard]:
    by_source: dict[str, list[ProofRecord]] = defaultdict(list)
    for record in records:
        if record.source not in EXCLUDED_SOURCES:
            by_source[record.source].append(record)
    unknown = sorted(set(by_source) - set(TRACE_ORDER))
    if unknown:
        raise ValueError(f"Sources without a tracing position: {unknown}")
    shards: list[TracingShard] = []
    for source in TRACE_ORDER:
        ordered = sorted(by_source[source], key=lambda record: stable_fraction(record.identifier, "order"))
        pilot, main = ordered[:pilot_size], ordered[pilot_size:]
        frequency = Counter(record.header for record in main)
        # Stable sort: proofs stay in hash order within a header, and headers are contiguous across shards.
        main.sort(key=lambda record: (-frequency[record.header], record.header))
        shards += _chunks(source, "pilot", pilot, shard_size) + _chunks(source, "main", main, shard_size)
    return shards


def most_common_header(shards: Iterable[TracingShard]) -> str:
    return Counter(record.header for shard in shards for record in shard.records).most_common(1)[0][0]


def plan_batches(shard: TracingShard, preloaded_header: str) -> list[TracingBatch]:
    by_header: dict[str, list[ProofRecord]] = defaultdict(list)
    for record in shard.records:
        by_header[record.header].append(record)
    batches: list[TracingBatch] = []
    for header, records in by_header.items():
        size = 1 if header == preloaded_header else FOREIGN_HEADER_BATCH_SIZE
        batches += [
            TracingBatch(shard.key, header, tuple(records[start : start + size]))
            for start in range(0, len(records), size)
        ]
    return batches


async def trace_shards(
    shards: Sequence[TracingShard],
    pool_size: int,
    config: LeanReplConfig,
    limits: TracingLimits,
    on_shard_traced: Callable[[TracingShard, list[ProofTrace]], Awaitable[None]],
    may_proceed: asyncio.Event,
) -> None:
    header = most_common_header(shards)
    planned = [(shard, plan_batches(shard, header)) for shard in shards]
    shards_by_key = {shard.key: shard for shard in shards}
    remaining_batches = {shard.key: len(batches) for shard, batches in planned}
    traces_by_shard: dict[str, list[ProofTrace]] = defaultdict(list)
    queue: asyncio.Queue[TracingBatch | None] = asyncio.Queue(maxsize=2 * pool_size)

    async def produce() -> None:
        for _, batches in planned:
            for batch in batches:
                await queue.put(batch)
        for _ in range(pool_size):
            await queue.put(None)

    async def work() -> None:
        while (batch := await queue.get()) is not None:
            await may_proceed.wait()
            try:
                traces = await trace_batch(pool, batch, header, limits)
            except Exception as error:
                logger.exception("Tracing a batch of %d proofs failed", len(batch.records))
                traces = repl_failure_traces(batch, error, limits)
            traces_by_shard[batch.shard_key].extend(traces)
            remaining_batches[batch.shard_key] -= 1
            if remaining_batches[batch.shard_key] == 0:
                await on_shard_traced(shards_by_key[batch.shard_key], traces_by_shard.pop(batch.shard_key))

    async with LeanReplPool(pool_size, config) as pool:
        await pool.start([header])
        await asyncio.gather(produce(), *(work() for _ in range(pool_size)))
